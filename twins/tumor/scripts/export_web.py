"""Data for the page's tumor panel: web/tumor_run.js. The page cannot run the model (a solve takes 17 s), so it replays
the twin's run of results/HGG_demo_001/twin_run_10.json and the forecasts computed here from it.

For each visit: the day, the cell count measured from the MRI, the count the twin expected before it, the parameters
after it, and, with those parameters, the cell count every 5 days to the last visit under the planned chemotherapy
and under totals of 30 to 70. All are model outputs; no image goes to the page.

Usage: python twins/tumor/scripts/export_web.py   (from the repository root; about 17 minutes on a laptop CPU)
"""
import json
import time
from pathlib import Path

from twins.tumor import Glioma
from twins.tumor.model import PARAMS

ROOT = Path(__file__).resolve().parents[3]
RUN = Path(__file__).resolve().parents[1] / "results" / "HGG_demo_001" / "twin_run_10.json"
DOSES = (30, 40, 50, 60, 70)

start = time.time()
run = json.loads(RUN.read_text())
g = Glioma(run["patient"])
last = g.day(g.dates[-1])
days = [float(d) for d in range(0, int(last) + 1, 5)]
visits = []
for v in run["visits"]:
    params = [v[p] for p in PARAMS]
    curves = {"plan": [g.cell_count(m) for m in g.solve(params, days)]}
    for dose in DOSES:
        curves[str(dose)] = [g.cell_count(m) for m in g.solve(params, days, chemo_total=dose)]
    visits.append(dict(day=v["day"], measured=v["measured"], expected=v["expected"],
                       params={p: v[p] for p in PARAMS}, curves=curves))
    print(f"visit on day {v['day']:g} done, {time.time() - start:.0f} s", flush=True)
data = dict(patient=run["patient"], steps=run["steps"], true_params=run["true_params"], days=days,
            planned_total=round(float(sum(g.doses)), 4), doses=list(DOSES), visits=visits)
out = ROOT / "web" / "tumor_run.js"
out.write_text("// Generated by twins/tumor/scripts/export_web.py; do not edit.\nwindow.TUMOR_RUN = "
               + json.dumps(data, separators=(",", ":")) + ";\n")
print("wrote", out)
